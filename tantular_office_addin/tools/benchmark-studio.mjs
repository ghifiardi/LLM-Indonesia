// --- Fixed source fixtures --------------------------------------------------
// Deterministic, checked-in text so every run (and every machine) measures
// the same input. Real report-shaped Indonesian prose, not lorem ipsum —
// closer to what the token-budget question actually depends on.

const PARAGRAPH =
  "Pertumbuhan adopsi model bahasa lokal di sektor publik Indonesia terus meningkat sejak 2024, " +
  "didorong oleh kebutuhan privasi data dan efisiensi biaya operasional. Beberapa instansi telah " +
  "melaporkan penghematan waktu proses dokumen hingga 40 persen setelah migrasi ke workflow berbasis " +
  "model lokal, meskipun tantangan seputar kapasitas komputasi dan pelatihan staf tetap menjadi " +
  "perhatian utama dalam perencanaan jangka menengah. ";

export function buildFixture(targetChars) {
  let text = "";
  while (text.length < targetChars) text += PARAGRAPH;
  return text.slice(0, targetChars);
}

export const FIXTURES = {
  short: buildFixture(600),
  medium: buildFixture(3200),
  long: buildFixture(15_500)
};

export const ALL_SECTION_COUNTS = [3, 6, 12];
export const DEFAULT_MODEL = "tantular-office:0.5-9b";

// Must match SETTINGS_KEY in src/tantularClient.js — this is the localStorage
// key loadSettings() reads to decide which model an actual request uses.
export const SETTINGS_STORAGE_KEY = "tantular.office.settings.v1";

// Mirrors src/document/documentPlanner.js's planDocument() formula exactly —
// duplicated here only so the benchmark can log what was REQUESTED without
// planDocument needing to expose an internal implementation detail. Keep in
// sync if that formula changes.
export function requestedMaxTokensFor(sectionCount) {
  return Math.min(6000, 1200 + sectionCount * 450);
}

// --- CLI argument parsing / execution planning (pure, testable) ------------

export function parseCliArgs(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith("--")) continue;
    const name = arg.slice(2);
    if (name === "all") { flags.all = true; continue; }
    const value = argv[i + 1];
    flags[name] = value;
    i += 1;
  }

  const fixtureArg = flags.all ? "all" : (flags.fixture || "short");
  const sectionsArg = flags.all ? "all" : (flags.sections || "3");
  // --temperature is a deprecated alias for --load-state (same meaning);
  // --load-state wins if both are somehow passed.
  if (flags.temperature && !flags["load-state"]) {
    console.warn("[benchmark] --temperature is deprecated; use --load-state (same meaning, less confusing next to model sampling temperature).");
  }
  const loadStateArg = flags["load-state"] || flags.temperature || "warm";
  const iterations = flags.iterations !== undefined ? Number(flags.iterations) : 1;
  const model = flags.model || DEFAULT_MODEL;
  const devOrigin = flags["dev-origin"] || "https://localhost:3000";
  const ollamaOrigin = flags["ollama-origin"] || "http://127.0.0.1:11434";
  const out = flags.out || path.join(root, "tools/benchmark-results.jsonl");

  const errors = [];
  if (!Number.isInteger(iterations) || iterations < 1) {
    errors.push(`--iterations must be a positive integer, got ${JSON.stringify(flags.iterations)}`);
  }
  if (!["short", "medium", "long", "all"].includes(fixtureArg)) {
    errors.push(`--fixture must be short|medium|long|all, got ${JSON.stringify(fixtureArg)}`);
  }
  if (!["3", "6", "12", "all"].includes(sectionsArg)) {
    errors.push(`--sections must be 3|6|12|all, got ${JSON.stringify(sectionsArg)}`);
  }
  if (!["cold", "warm", "both"].includes(loadStateArg)) {
    errors.push(`--load-state must be cold|warm|both, got ${JSON.stringify(loadStateArg)}`);
  }

  const fixtures = fixtureArg === "all" ? Object.keys(FIXTURES) : [fixtureArg];
  const sections = sectionsArg === "all" ? ALL_SECTION_COUNTS : [Number(sectionsArg)];
  const loadStates = loadStateArg === "both" ? ["cold", "warm"] : [loadStateArg];

  return {
    errors, fixtures, sections, loadStates, iterations, model,
    devOrigin, ollamaOrigin, out
  };
}

// One ordered entry per MEASURED run. Grouped by (fixture, sectionCount,
// loadState) with all iterations of one group contiguous, so cold and warm
// results are never interleaved within a scenario.
export function buildRunPlan({ fixtures, sections, loadStates, iterations }) {
  const plan = [];
  for (const fixture of fixtures) {
    for (const sectionCount of sections) {
      for (const loadState of loadStates) {
        for (let iteration = 0; iteration < iterations; iteration += 1) {
          plan.push({ fixture, sectionCount, loadState, iteration });
        }
      }
    }
  }
  return plan;
}

// A requested cold/warm state only becomes the row's verifiedLoadState if
// preparation actually confirmed it (model absent from /api/ps after
// unload, or present after warm-up) — otherwise the row is "unknown" and
// must be excluded from any median/p95 computed later, rather than silently
// counted as the state that was merely requested but never confirmed.
export function verifiedLoadStateFor(requestedLoadState, confirmed) {
  if (requestedLoadState === "cold") return confirmed ? "cold" : "unknown";
  if (requestedLoadState === "warm") return confirmed ? "warm" : "unknown";
  return "unknown";
}

// --- Narrow HTTPS fetch adapter ---------------------------------------------
// Node's built-in global fetch (undici) does not honor a plain https.Agent
// passed via an `agent` init option, and this repo does not depend on
// undici directly for a dispatcher-based workaround. This is a minimal
// fetch-shaped adapter over node:https for exactly what tantularClient.js's
// fetch calls need: method/headers/body/signal in, {ok,status,json,text}
// out. Ollama's plain-HTTP endpoints don't need this — the real global
// fetch handles those directly.
export function httpsFetch(url, init = {}) {
  return new Promise((resolve, reject) => {
    const target = new URL(url);
    const req = https.request({
      hostname: target.hostname,
      port: target.port || 443,
      path: `${target.pathname}${target.search}`,
      method: init.method || "GET",
      headers: init.headers || {},
      rejectUnauthorized: false // the local dev-server's cert is self-signed by design
    }, (res) => {
      const chunks = [];
      res.on("data", (chunk) => chunks.push(chunk));
      res.on("end", () => {
        const bodyText = Buffer.concat(chunks).toString("utf8");
        resolve({
          ok: (res.statusCode || 0) >= 200 && (res.statusCode || 0) < 300,
          status: res.statusCode || 0,
          headers: res.headers,
          json: async () => JSON.parse(bodyText || "{}"),
          text: async () => bodyText
        });
      });
    });
    req.on("error", reject);
    if (init.signal) {
      if (init.signal.aborted) {
        req.destroy();
        reject(Object.assign(new Error("aborted"), { name: "AbortError" }));
        return;
      }
      init.signal.addEventListener("abort", () => {
        req.destroy();
        reject(Object.assign(new Error("aborted"), { name: "AbortError" }));
      }, { once: true });
    }
    if (init.body) req.write(init.body);
    req.end();
  });
}

// Installs the fetch router (dev-server HTTPS support) and the minimal
// window/localStorage shims tantularClient.js needs, so that BOTH preflight
// and every later call go through the same, already-tested path — nothing
// downstream (preflight included) ever touches the raw, HTTPS-incapable
// global fetch again after this runs.
export function installEnvironment({ devOrigin, model }) {
  const realFetch = globalThis.fetch;
  globalThis.fetch = (url, init) => {
    const absolute = String(url).startsWith("http") ? url : `${devOrigin}${url}`;
    return absolute.startsWith("https:") ? httpsFetch(absolute, init) : realFetch(absolute, init);
  };
  globalThis.window = {
    ...globalThis.window,
    setTimeout: globalThis.setTimeout,
    clearTimeout: globalThis.clearTimeout,
    location: { hostname: "localhost" }
  };
  globalThis.location = globalThis.location || { hostname: "localhost" };
  // Makes loadSettings() (src/tantularClient.js) resolve deckModel to
  // exactly --model, so the ACTUAL outbound request carries the model this
  // harness claims to be benchmarking, not the client's own default.
  globalThis.localStorage = {
    getItem: (key) => (key === SETTINGS_STORAGE_KEY ? JSON.stringify({ deckModel: model }) : null),
    setItem: () => {}
  };
}

// --- Machine / environment info (best-effort; null when unavailable) -------

export function machineModel() {
  try {
    if (process.platform === "darwin") {
      return execFileSync("sysctl", ["-n", "hw.model"], { encoding: "utf8" }).trim();
    }
  } catch {
    // fall through
  }
  return `${os.type()} ${os.arch()}`;
}

export async function ollamaVersion(ollamaOrigin) {
  try {
    const res = await fetch(`${ollamaOrigin}/api/version`);
    const data = await res.json();
    return data?.version || null;
  } catch {
    return null;
  }
}

export async function listOllamaModels(ollamaOrigin) {
  const res = await fetch(`${ollamaOrigin}/api/tags`);
  const data = await res.json();
  return data?.models || [];
}

export async function modelInfo(ollamaOrigin, modelName) {
  try {
    const models = await listOllamaModels(ollamaOrigin);
    const entry = models.find((m) => m.name === modelName || m.model === modelName);
    return {
      digest: entry?.digest || null,
      quantization: entry?.details?.quantization_level || null,
      parameterSize: entry?.details?.parameter_size || null
    };
  } catch {
    return { digest: null, quantization: null, parameterSize: null };
  }
}

export async function isModelWarm(ollamaOrigin, modelName) {
  try {
    const res = await fetch(`${ollamaOrigin}/api/ps`);
    const data = await res.json();
    return (data?.models || []).some((m) => m.name === modelName || m.model === modelName);
  } catch {
    return false;
  }
}

// Ollama unloads a model as soon as a request against it carries
// keep_alive: 0. The request itself must still be valid (empty prompt is
// fine) — this is the documented mechanism, not a side effect of a normal
// call.
export async function unloadModel(ollamaOrigin, modelName) {
  try {
    await fetch(`${ollamaOrigin}/api/generate`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ model: modelName, keep_alive: 0 })
    });
  } catch {
    // best-effort — waitUntilUnloaded below is the real guarantee
  }
}

export async function waitUntilUnloaded(ollamaOrigin, modelName, timeoutMs = 30_000) {
  const startedAt = Date.now();
  while (Date.now() - startedAt < timeoutMs) {
    // eslint-disable-next-line no-await-in-loop
    if (!(await isModelWarm(ollamaOrigin, modelName))) return true;
    // eslint-disable-next-line no-await-in-loop
    await new Promise((resolve) => { setTimeout(resolve, 500); });
  }
  return false;
}

// --- Preflight ---------------------------------------------------------------
// No model call is ever issued unless the dev-server is reachable, Ollama is
// reachable, AND the requested model is actually installed there. Call this
// ONLY after installEnvironment() — it uses the same fetch (`fetch`, the
// global) that every later call uses, specifically so preflight tests the
// path a real run would actually take (including the HTTPS adapter), not a
// separately-behaving one.
export async function preflight({ devOrigin, ollamaOrigin, model, requireJsonSchema = false }) {
  try {
    const devRes = await fetch(`${devOrigin}/src/taskpane.html`);
    if (!devRes.ok) return { ok: false, reason: `dev-server at ${devOrigin} responded ${devRes.status}` };
  } catch (error) {
    return { ok: false, reason: `dev-server at ${devOrigin} unreachable: ${error.message}` };
  }
  try {
    const ollamaRes = await fetch(`${ollamaOrigin}/api/version`);
    if (!ollamaRes.ok) return { ok: false, reason: `Ollama at ${ollamaOrigin} responded ${ollamaRes.status}` };
  } catch (error) {
    return { ok: false, reason: `Ollama at ${ollamaOrigin} unreachable: ${error.message}` };
  }
  // Measured generation always travels through THIS dev-server's own
  // configured upstream (its OLLAMA_PORT), independent of --ollama-origin —
  // the latter only drives metadata/load-state checks below. Without this,
  // --ollama-origin pointing at a DIFFERENT Ollama than the one the
  // Companion actually generates against would silently attribute one
  // runtime's digest/quantization/load-state to another's generation.
  let diag;
  try {
    const diagRes = await fetch(`${devOrigin}/api/diagnostics`);
    if (!diagRes.ok) {
      return { ok: false, reason: `dev-server at ${devOrigin} could not report its configured Ollama origin (${diagRes.status})` };
    }
    diag = await diagRes.json();
    if (diag?.ollamaOrigin !== ollamaOrigin) {
      return {
        ok: false,
        reason: `--ollama-origin (${ollamaOrigin}) does not match the Companion's own configured Ollama ` +
          `(${diag?.ollamaOrigin || "unknown"}) — measured generation travels through the Companion's Ollama, ` +
          "not the one this harness would inspect. Pass the matching --ollama-origin, or restart the Companion " +
          "with a matching TANTULAR_OLLAMA_PORT."
      };
    }
  } catch (error) {
    return { ok: false, reason: `could not verify the Companion's configured Ollama origin: ${error.message}` };
  }
  // 2026-08-31: a Companion process started before a bridge change was saved
  // to disk keeps running the old in-memory bridge — Node does not hot-reload
  // ES module imports. A schema benchmark run against that stale process
  // "proves" nothing about schema enforcement; it silently exercised the old
  // json_object path instead. Refuse outright rather than produce data that
  // looks like a schema result but isn't one.
  if (requireJsonSchema && diag?.bridgeCapabilities?.jsonSchema !== true) {
    return {
      ok: false,
      reason: `dev-server at ${devOrigin} reports bridgeCapabilities.jsonSchema is not true — this Companion process ` +
        "predates the JSON-Schema bridge (or the bridge failed to load it) and cannot be used for a schema benchmark. " +
        "Restart the Companion (stop the npm start supervisor, then `npm start` again) and re-run preflight."
    };
  }
  // 2026-08-31: companionBootId alone identifies a process instance, not
  // whether that instance predates the source code currently on disk — the
  // exact ambiguity that produced one invalid reliability gate already, and
  // recurred a second time after the very fix for the first occurrence
  // (jsonSchema:true was already present in the bridge revision that shipped
  // the fix, so the capability flag alone could not catch a bridge that
  // predates the LATER telemetry change). Comparing the running process's
  // self-reported bridgeRevision against the revision this harness's own
  // import of ollamaBridge.js carries closes that gap for good: it is a
  // build-identity check, not a feature-presence check.
  if (requireJsonSchema && diag?.bridgeRevision !== BRIDGE_REVISION) {
    return {
      ok: false,
      reason: `dev-server at ${devOrigin} reports bridgeRevision "${diag?.bridgeRevision || "unknown"}", but this harness ` +
        `expects "${BRIDGE_REVISION}" — the running Companion process predates the current source. ` +
        "Restart the Companion (stop the npm start supervisor, then `npm start` again) and re-run preflight."
    };
  }
  if (model) {
    let models;
    try {
      models = await listOllamaModels(ollamaOrigin);
    } catch (error) {
      return { ok: false, reason: `could not list Ollama models to verify "${model}" is installed: ${error.message}` };
    }
    const installed = models.some((m) => m.name === model || m.model === model);
    if (!installed) {
      return { ok: false, reason: `model "${model}" is not installed in Ollama. Run: ollama pull ${model}` };
    }
  }
  return { ok: true, reason: "", diag };
}

// --- One measured call -------------------------------------------------------
// planDocument is imported lazily (only once main() actually needs it) so
// unit tests can import this file's pure helpers without ever touching
// tantularClient.js's window/localStorage requirements.
// Pure classification, deliberately conservative: a row counts toward any
// median/p95 ONLY when nothing about it is questionable. This is safer than
// relying on a later analyst to remember every exclusion rule — the row
// says outright whether it's usable and, if not, exactly which single
// condition disqualified it (checked in this fixed priority order, so two
// simultaneous problems still report one clear reason rather than picking
// arbitrarily).
// Every numeric field a real Ollama response carries — a metrics object
// missing even one (e.g. only { model } survived some upstream reshaping)
// is exactly as unusable for a median/p95 as no metrics at all, so it must
// not slip through as "valid" just because the object itself is truthy.
const REQUIRED_METRIC_FIELDS = [
  "promptTokens", "completionTokens", "loadDurationMs",
  "promptEvalDurationMs", "evalDurationMs", "totalDurationMs", "tokensPerSecond"
];

function hasCompleteMetrics(metrics) {
  return Boolean(metrics) && REQUIRED_METRIC_FIELDS.every((key) => Number.isFinite(metrics[key]));
}

export function classifyRow({ outcome, modelMismatch, requestedLoadState, verifiedLoadState, metrics }) {
  let invalidReason = null;
  if (outcome === "fallback") invalidReason = "fallback";
  else if (outcome !== "success") invalidReason = "timeout_or_error";
  else if (modelMismatch) invalidReason = "model_mismatch";
  else if (verifiedLoadState !== requestedLoadState) invalidReason = "unknown_load_state";
  else if (!hasCompleteMetrics(metrics)) invalidReason = "missing_metrics";
  return { validForStats: invalidReason === null, invalidReason };
}

export async function runOne({
  planDocumentFn, fixture, sourceText, sectionCount,
  requestedModel, requestedLoadState, verifiedLoadState
}) {
  let metrics = null;
  const startedAt = Date.now();
  let outcome = "success";
  try {
    const result = await planDocumentFn({
      brief: sourceText,
      documentType: "Laporan profesional",
      sectionCount,
      onMetrics: (m) => { metrics = m; }
    });
    if (result.source !== "model") outcome = "fallback";
  } catch (error) {
    outcome = error?.name === "AbortError" ? "cancelled" : "timeout_or_error";
  }
  const wallClockMs = Date.now() - startedAt;
  const actualModel = metrics?.model ?? null;
  const modelMismatch = actualModel !== null && actualModel !== requestedModel;
  const { validForStats, invalidReason } = classifyRow({
    outcome, modelMismatch, requestedLoadState, verifiedLoadState, metrics
  });

  // Allowlisted fields only — no prompt/response text and no API key ever
  // reaches this row, by construction (nothing above reads either into a
  // local variable that ends up here).
  return {
    timestamp: new Date(startedAt).toISOString(),
    fixture,
    sectionCount,
    sourceChars: sourceText.length,
    requestedMaxTokens: requestedMaxTokensFor(sectionCount),
    requestedModel,
    actualModel,
    modelMismatch,
    promptTokens: metrics?.promptTokens ?? null,
    completionTokens: metrics?.completionTokens ?? null,
    loadDurationMs: metrics?.loadDurationMs ?? null,
    promptEvalDurationMs: metrics?.promptEvalDurationMs ?? null,
    evalDurationMs: metrics?.evalDurationMs ?? null,
    ollamaTotalDurationMs: metrics?.totalDurationMs ?? null,
    wallClockMs,
    tokensPerSecond: metrics?.tokensPerSecond ?? null,
    requestedLoadState,
    verifiedLoadState,
    studioCacheBypassed: true,
    outcome,
    validForStats,
    invalidReason
  };
}

// --- Main --------------------------------------------------------------------
// Dependency-injectable (runOneFn, planDocumentFn) so tests can drive the
// orchestration logic (preflight gating, plan sizing, row shape) without
// making a real model call.
export async function main(argv, { runOneFn = runOne, loadPlanDocument } = {}) {
  const args = parseCliArgs(argv);
  if (args.errors.length) {
    for (const err of args.errors) console.error(`[benchmark] ${err}`);
    process.exitCode = 1;
    return;
  }

  const runPlan = buildRunPlan(args);
  console.log(
    `[benchmark] plan: fixtures=${args.fixtures.join(",")} sections=${args.sections.join(",")} ` +
    `load-state=${args.loadStates.join("+")} iterations=${args.iterations} model=${args.model}\n` +
    `[benchmark] measured calls: ${runPlan.length}\n` +
    `[benchmark] dev-origin=${args.devOrigin} ollama-origin=${args.ollamaOrigin} out=${args.out}`
  );
  if (args.iterations < 20) {
    console.warn(
      `[benchmark] --iterations ${args.iterations} is below the 20-30 needed for a real p95. ` +
      "Report median, p90, and max from this run instead of calling anything p95."
    );
  }
  if (runPlan.some((r) => r.loadState === "cold")) {
    console.warn("[benchmark] cold runs unload the model before EVERY measured iteration — this is slow and expensive.");
  }

  // Installed BEFORE preflight so preflight exercises the exact same
  // HTTPS-capable path (and the same model-selection stub) every measured
  // call will use — not a separately-behaving raw fetch that could pass
  // while the real path would have failed.
  installEnvironment(args);

  const preflightResult = await preflight(args);
  if (!preflightResult.ok) {
    console.error(`[benchmark] preflight failed: ${preflightResult.reason}`);
    console.error("[benchmark] no model calls were made.");
    process.exitCode = 1;
    return;
  }

  const planDocumentFn = loadPlanDocument
    ? await loadPlanDocument()
    : (await import(path.join(root, "src/document/documentPlanner.js"))).planDocument;

  const [ram, version, info] = [
    Math.round(os.totalmem() / 1024 ** 3),
    await ollamaVersion(args.ollamaOrigin),
    await modelInfo(args.ollamaOrigin, args.model)
  ];
  const machine = machineModel();
  console.log(`[benchmark] machine=${machine} ramGB=${ram} ollama=${version} ` +
    `digest=${info.digest?.slice(0, 12) || "unknown"} quant=${info.quantization || "unknown"}`);

  for (const entry of runPlan) {
    let verifiedLoadState;
    if (entry.loadState === "cold") {
      console.log(`[benchmark] unloading ${args.model} for a cold run...`);
      // eslint-disable-next-line no-await-in-loop
      await unloadModel(args.ollamaOrigin, args.model);
      // eslint-disable-next-line no-await-in-loop
      const unloaded = await waitUntilUnloaded(args.ollamaOrigin, args.model);
      verifiedLoadState = verifiedLoadStateFor("cold", unloaded);
      if (verifiedLoadState === "unknown") {
        console.warn("[benchmark] model still shows as loaded after the unload timeout — recording this row as verifiedLoadState: unknown, NOT cold.");
      }
    } else {
      // eslint-disable-next-line no-await-in-loop
      let warm = await isModelWarm(args.ollamaOrigin, args.model);
      if (!warm) {
        console.log("[benchmark] model not warm before a warm-labeled run — issuing an unmeasured warm-up call...");
        // eslint-disable-next-line no-await-in-loop
        await runOneFn({
          planDocumentFn, fixture: "warmup", sourceText: FIXTURES.short, sectionCount: 3,
          requestedModel: args.model, requestedLoadState: "warm", verifiedLoadState: "warm"
        });
        // eslint-disable-next-line no-await-in-loop
        warm = await isModelWarm(args.ollamaOrigin, args.model);
      }
      verifiedLoadState = verifiedLoadStateFor("warm", warm);
      if (verifiedLoadState === "unknown") {
        console.warn("[benchmark] model still does not appear in /api/ps after warm-up — recording this row as verifiedLoadState: unknown, NOT warm.");
      }
    }

    console.log(`[benchmark] ${entry.fixture} x ${entry.sectionCount} sections [requested ${entry.loadState}, verified ${verifiedLoadState}], ` +
      `iteration ${entry.iteration + 1}/${args.iterations}...`);
    // eslint-disable-next-line no-await-in-loop
    const row = await runOneFn({
      planDocumentFn,
      fixture: entry.fixture,
      sourceText: FIXTURES[entry.fixture],
      sectionCount: entry.sectionCount,
      requestedModel: args.model,
      requestedLoadState: entry.loadState,
      verifiedLoadState
    });
    row.machineModel = machine;
    row.ramGB = ram;
    row.ollamaVersion = version;
    row.modelDigest = info.digest;
    row.quantization = info.quantization;
    row.devOrigin = args.devOrigin;
    row.ollamaOrigin = args.ollamaOrigin;
    if (row.modelMismatch) {
      console.warn(`[benchmark] MODEL MISMATCH: requested ${row.requestedModel} but the response was generated by ${row.actualModel}. This row is likely invalid for a --model comparison.`);
    }
    // eslint-disable-next-line no-await-in-loop
    await appendFile(args.out, `${JSON.stringify(row)}\n`);
    console.log(`[benchmark]   -> ${row.outcome} in ${row.wallClockMs}ms ` +
      `(${row.completionTokens ?? "?"} tokens, ${row.tokensPerSecond ?? "?"} tok/s)`);
  }
  console.log(`[benchmark] done — ${runPlan.length} row(s) appended to ${args.out}`);
}

// A raw `import.meta.url === \`file://${process.argv[1]}\`` string compare
// silently NEVER matches when the invocation path is relative (the normal
// case: `node tools/benchmark-studio.mjs`) or contains characters
// import.meta.url URL-encodes (this repo's own path has a literal "&") —
// the exact conditions the documented CLI usage in this file hits. That
// bug looks like success: main() is simply never called, exit code 0, no
// output file, no error. Comparing resolved filesystem paths instead of
// raw strings is immune to both relative-vs-absolute and encoding
// mismatches.
export function isMainModule(metaUrl, argv1) {
  if (!argv1) return false;
  try {
    return fileURLToPath(metaUrl) === path.resolve(argv1);
  } catch {
    return false;
  }
}
if (isMainModule(import.meta.url, process.argv[1])) {
  main(process.argv.slice(2)).catch((error) => {
    console.error("[benchmark] fatal:", error);
    process.exitCode = 1;
  });
}
