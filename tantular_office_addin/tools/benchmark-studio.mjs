#!/usr/bin/env node
// Studio generation benchmark harness — PREPARED, NOT YET RUN.
//
// Purpose: measure whether a future performance change (lower output-token
// budgets, a lighter model/quantization, chunked generation, Cloud vs Local)
// actually helps, instead of guessing. Every measured row is one real call
// through the ACTUAL planDocument() code path — same prompts, same maxTokens
// formula — not a re-implementation of it.
//
// Requires, before running:
//   1. `npm run dev` (or `npm start`) already running on --dev-origin
//      (default https://localhost:3000).
//   2. Ollama running locally on --ollama-origin (default
//      http://127.0.0.1:11434) with the target --model pulled. Preflight
//      checks this specifically and refuses to run otherwise.
// No model call is ever issued unless the fetch router + settings stub are
// installed AND preflight (reachability of both origins, plus the requested
// model's presence) has passed.
//
// Usage (this file has no --help flag; this comment IS the reference):
//   node tools/benchmark-studio.mjs
//     Safe default: one short-source, 3-section, 1-iteration, warm call.
//   node tools/benchmark-studio.mjs --all --iterations 20 --load-state both
//     The full 3-fixture x 3-section matrix, 20 iterations each, both cold
//     and warm — this is what a real median/p95 needs, and it is expensive:
//     --load-state both issues up to 2x the measured calls, plus one full
//     model unload+reload before every COLD iteration.
//
// Flags:
//   --model <name>            Studio model to benchmark (default:
//                              tantular-office:0.5-9b). This is the model
//                              actually requested in every generation call
//                              (see "Model selection" below) — not just a
//                              label attached to the output rows.
//   --fixture short|medium|long|all   (default: short)
//   --sections 3|6|12|all              (default: 3)
//   --all                      Shorthand for --fixture all --sections all
//   --load-state cold|warm|both        (default: warm). --temperature is
//                              accepted as a deprecated alias (kept because
//                              an earlier revision of this harness used it;
//                              it means the SAME thing as --load-state here,
//                              nothing to do with model sampling temperature).
//   --iterations N             positive integer (default: 1)
//   --out <path>               JSONL output path (default: tools/benchmark-results.jsonl)
//   --dev-origin <url>         (default: https://localhost:3000)
//   --ollama-origin <url>      (default: http://127.0.0.1:11434)
//
// Model selection: planDocument()/runTantular() choose their model via
// tantularClient.js's loadSettings(), which reads localStorage — outside a
// real Office webview there is no localStorage, so without help every
// request would silently fall back to the client's own hardcoded default,
// NOT --model. This harness installs a minimal localStorage stub (see
// installEnvironment() below) whose settings.deckModel is exactly --model,
// so the actual outbound request really does carry the requested model. It
// also compares --model (requestedModel) against the model the response's
// own metrics report it was generated by (actualModel, from
// tantular_metrics) on every row, and flags modelMismatch: true if they
// differ — trust the row's actualModel/modelMismatch fields over its
// requestedModel field if you ever see them disagree.
//
// Output: one JSON object per line (JSONL) per MEASURED run — warm-up
// preparation calls are never recorded as measured rows. Fields: timestamp,
// fixture, sectionCount, sourceChars, requestedMaxTokens, requestedModel,
// actualModel (the model the RESPONSE itself reports, not just what was
// requested), modelMismatch, promptTokens, completionTokens, loadDurationMs,
// promptEvalDurationMs, evalDurationMs, ollamaTotalDurationMs, wallClockMs,
// tokensPerSecond, requestedLoadState, verifiedLoadState (cold|warm|unknown
// — "unknown" means preparation could not be confirmed), studioCacheBypassed
// (always true — see note below), outcome, validForStats (boolean —
// computed for you; filter on this instead of re-deriving the exclusion
// rules yourself), invalidReason (null when validForStats is true, else one
// of "fallback" | "timeout_or_error" | "model_mismatch" |
// "unknown_load_state" | "missing_metrics"), machineModel, ramGB,
// ollamaVersion, modelDigest, quantization, devOrigin, ollamaOrigin. No
// prompt text, response text, or API key is ever included in a row.
//
// Cache note: this harness calls planDocument() directly, which has no
// knowledge of the taskpane's Studio spec cache (src/chat/studioCache.js) —
// every row here is a real model call, by construction. That cache's
// correctness is already covered separately by tests/studioCache*.test.mjs;
// this harness measures generation cost, not cache behavior, so every row
// carries studioCacheBypassed: true rather than a cacheHitOrMiss field that
// would misleadingly suggest this harness could ever observe a hit.
//
// IMPORTANT — do not trust a small "p95": with fewer than 20 measured
// iterations per (fixture, sectionCount, load-state) scenario, report
// median, p90, and max instead of labeling anything p95.
//
// This script makes no performance claim itself. It only produces the rows
// a human (or a later analysis pass) needs to make one.

